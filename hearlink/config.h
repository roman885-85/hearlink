// Сколько миллисекунд прошло с отметки t. Отметку может обновить другая задача (приём, передача) уже после того,
// как здесь прочитали время: разность выходит «минус одна миллисекунда» и без знака превращается в 49 суток.
// Так сторож радио несколько раз в минуту ложно перезапускал радио, а приёмник уходил искать канал (06.10).
static inline uint32_t msSince(uint32_t t, uint32_t now) {
  int32_t d = (int32_t)(now - t);
  return d < 0 ? 0 : (uint32_t)d;
}
static inline uint32_t msSince(uint32_t t) {
  return msSince(t, millis());
}

