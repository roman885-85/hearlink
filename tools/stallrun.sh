#!/bin/sh
# Прогон «встаёт ли радио передатчика»: раз в минуту спрашивает у передатчика `?` и `Q` и печатает одну строку —
# сколько работает, какой вход, один или два кадра в пакете, сколько раз вставало радио, время обработки кадра.
#
#   tools/stallrun.sh <порт> <вход: a0 | a1 | a2 | -> <пакеты: Qd0 | Qd1 | Qd2 | -> <минут> [папка для отчётов]
#
#   a0 — встроенный АЦП, a1 — PCM1808, a2 — I2S без такта (каждая из них ПЕРЕЗАПУСКАЕТ передатчик); «-» — не менять.
#   Qd0 — одиночные пакеты, Qd1 — двойные, когда все приёмники умеют (так по умолчанию), Qd2 — всегда двойные.
#   Упаковка действует до перезапуска. После прогона вход и упаковку вернуть самому (обычно: a1, Qd1).
#   С живым входом PCM1808 в эфире (проверочный звук выключен) порт молчит — такой прогон этим средством не снять.
#   Компьютер на время прогона не должен уснуть (10.10 он уснул на 51 минуту посреди замера): запускать под
#   caffeinate -i tools/stallrun.sh …
cd "$(dirname "$0")/.."
P=${1:?порт}; IN=${2:?вход: a0 | a1 | a2 | -}; DB=${3:?пакеты: Qd0 | Qd1 | Qd2 | -}; MIN=${4:?минут}
D=${5:-$(mktemp -d)}
mkdir -p "$D"
if [ "$IN" != - ]; then python3 tools/port.py "$P" 5 "$IN" > /dev/null 2>&1; sleep 22; fi
if [ "$DB" != - ]; then python3 tools/port.py "$P" 4 "$DB" > "$D/0.txt" 2>&1; fi
i=1
while [ "$i" -le "$MIN" ]; do
  sleep 50
  python3 tools/port.py "$P" 6 '?' Q > "$D/$i.txt" 2>&1
  echo "$(date '+%H:%M:%S') $(grep -a -o 'версія [0-9.]*' "$D/$i.txt" | head -1); $(grep -a -o 'працює [0-9]* с' "$D/$i.txt" | head -1); $(grep -a -o 'вхід: [^,]*' "$D/$i.txt" | head -1); $(grep -a -o 'ДВА кадри в пакеті\|один кадр у пакеті' "$D/$i.txt" | head -1); $(grep -a -o 'ставало [0-9]* разів, оживлено без перезапуску плати [0-9]*, швидких перезапусків плати [0-9]*' "$D/$i.txt" | head -1); кадр $(grep -a -o 'з минулого Q: сер. [0-9]* мкс' "$D/$i.txt" | head -1 | grep -o '[0-9]* мкс'), $(grep -a -o 'радіо [0-9]* решта' "$D/$i.txt" | tail -1 | grep -o 'радіо [0-9]*'); $(grep -a -o 'поверх попереднього [0-9]* %' "$D/$i.txt" | head -1); $(grep -a -o 'сер. [0-9]* мкс, найдовше [0-9]* мкс$' "$D/$i.txt" | head -1 | sed 's/^/наодинці /')"
  i=$((i + 1))
done
python3 tools/port.py "$P" 5 P > "$D/P.txt" 2>&1
grep -a "приймач [0-9A-F]* «" "$D/P.txt" | sed -E 's/^ *[0-9.]+ +//; s/, гучність [0-9]+//; s/, версія.*//' | cut -c1-170 | tail -2
echo "отчёты: $D"
