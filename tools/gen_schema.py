"""Рисует схемы соединений: docs/skhema-peredatchik.svg и docs/skhema-priemnik-<плата>.svg (+ .png).
Запуск: python3 tools/gen_schema.py"""
import os, subprocess

RED, BLK, BLU, GRN, VIO, ORG, AUD, GRY = '#c0392b', '#222', '#1f6fb2', '#2e8b57', '#7d4bb0', '#d2691e', '#00796b', '#777'
DOCS = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'docs')
o = []


def line(pts, c=BLK, w=2, dash=False):
    o.append('<polyline points="%s" fill="none" stroke="%s" stroke-width="%s" stroke-linejoin="round"%s/>'
             % (' '.join('%g,%g' % p for p in pts), c, w, ' stroke-dasharray="7 5"' if dash else ''))


def text(x, y, s, size=14, anchor='start', c='#111', bold=False):
    o.append('<text x="%g" y="%g" font-size="%g" text-anchor="%s" fill="%s"%s>%s</text>'
             % (x, y, size, anchor, c, ' font-weight="bold"' if bold else '', s))


def block(x, y, w, h, title, sub=None, dash=False):
    o.append('<rect x="%g" y="%g" width="%g" height="%g" rx="8" fill="%s" stroke="%s" stroke-width="2"%s/>'
             % (x, y, w, h, '#fbfbfb' if dash else '#f4f6f8', GRY if dash else '#333', ' stroke-dasharray="8 6"' if dash else ''))
    text(x + w / 2, y + 24, title, 15, 'middle', bold=True)
    if sub:
        text(x + w / 2, y + 42, sub, 12, 'middle', '#555')


def pin(x, y, name, side):
    o.append('<circle cx="%g" cy="%g" r="4" fill="#fff" stroke="#333" stroke-width="2"/>' % (x, y))
    text(x + (10 if side == 'l' else -10), y + 5, name, 13, 'start' if side == 'l' else 'end')


def dot(x, y, c=AUD):
    o.append('<circle cx="%g" cy="%g" r="4.5" fill="%s"/>' % (x, y, c))


def gnd(x, y):
    line([(x, y), (x, y + 12)])
    for i, hw in enumerate((11, 7, 3)):
        line([(x - hw, y + 12 + i * 5), (x + hw, y + 12 + i * 5)])


def res_h(x, y, label, c=AUD):
    o.append('<rect x="%g" y="%g" width="56" height="18" fill="#fff" stroke="%s" stroke-width="2"/>' % (x, y - 9, c))
    text(x + 28, y - 15, label, 12, 'middle')


def res_v(x, y, name, val, c=AUD, side='l'):
    o.append('<rect x="%g" y="%g" width="18" height="56" fill="#fff" stroke="%s" stroke-width="2"/>' % (x - 9, y, c))
    tx, an = (x - 15, 'end') if side == 'l' else (x + 15, 'start')
    text(tx, y + 26, name, 12, an)
    text(tx, y + 41, val, 12, an)


def cap_h(x, y, label, c=AUD):
    o.append('<rect x="%g" y="%g" width="9" height="28" fill="#fff" stroke="none"/>' % (x - 4.5, y - 14))
    line([(x - 4, y - 13), (x - 4, y + 13)], c, 3)
    line([(x + 4, y - 13), (x + 4, y + 13)], c, 3)
    text(x, y - 19, label, 12, 'middle')


def cap_v(x, y, name, val, c=AUD):
    o.append('<rect x="%g" y="%g" width="28" height="9" fill="#fff" stroke="none"/>' % (x - 14, y - 4.5))
    line([(x - 13, y - 4), (x + 13, y - 4)], c, 3)
    line([(x - 13, y + 4), (x + 13, y + 4)], c, 3)
    text(x + 19, y - 2, name, 12)
    text(x + 19, y + 13, val, 12)


def term(x, y, name):
    o.append('<circle cx="%g" cy="%g" r="8" fill="#fff" stroke="%s" stroke-width="3"/>' % (x, y, AUD))
    text(x - 14, y + 5, name, 13, 'end')


def save(name, W, H):
    body = '<rect width="%d" height="%d" fill="#fff"/>%s' % (W, H, '\n'.join(o))
    head = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" font-family="Helvetica, Arial, sans-serif">'
    path = os.path.join(DOCS, name + '.svg')
    open(path, 'w', encoding='utf-8').write(head % (W, H, W, H) + body + '</svg>')
    del o[:]
    # картинка для просмотра — средствами macOS, вдвое крупнее
    big = os.path.join(DOCS, name + '.x2.svg')
    open(big, 'w', encoding='utf-8').write(head % (W, H, W * 2, H * 2) + body + '</svg>')
    subprocess.call(['sips', '-s', 'format', 'png', big, '--out', os.path.join(DOCS, name + '.png')],
                    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    os.remove(big)
    print('ok', os.path.normpath(path))


