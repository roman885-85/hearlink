// Перерахунок частоти відліків (асинхронний) для мосту: вхід (АЦП PCM1808 або AES) іде своїм кварцом, вихід —
// тактом передавача (32 кГц). Стерео, вхід int16, вихід — 24 біти в int32.
//
// Як працює. Вхідні кадри складаються в кільце. Для кожного вихідного кадру береться дробова позиція у вхідному
// потоці (pos, Q32.32) і рахується сума T сусідніх вхідних відліків з вагами фільтра для цієї дробової частини.
// Фільтр — вікно Кайзера × sinc зі зрізом 16 кГц (половина 32 кГц): він і згладжує, і не дає частотам вище 16 кГц
// перекинутися вниз. Ваги заготовлені для ASRC_PHASES дробових положень; між сусідніми положеннями — лінійно.
// Крок pos на вихідний кадр = f_вх / f_вих; його підправляє регулятор за наповненням кільця (asrc_steer), бо обидва
// кварци «пливуть» на десятки ppm.
//
// Код без залежностей від RP2040 — той самий файл перевіряється на Mac (bridge/test/asrc_test.c).
#pragma once
#include <stdint.h>
#include <stdbool.h>

#ifndef ASRC_FAST
#if defined(PICO_ON_DEVICE) && PICO_ON_DEVICE
#define ASRC_FAST __attribute__((section(".time_critical.asrc")))   // RP2040: з ОЗП, не з флешу (кеш флешу малий)
#else
#define ASRC_FAST
#endif
#endif

#define ASRC_PHASES_BITS 8
#define ASRC_PHASES (1 << ASRC_PHASES_BITS)   // дробових положень на вхідний відлік
#define ASRC_MAX_TAPS 64                        // відводів (вхідних відліків) на один вихідний (44,1/48 кГц — 64)
#define ASRC_IN_BITS 11
#define ASRC_IN_SIZE (1u << ASRC_IN_BITS)       // вхідне кільце: 2048 кадрів (43 мс при 48 кГц)
#define ASRC_IN_MASK (ASRC_IN_SIZE - 1)

typedef struct {
  // Вхідне кільце записується двічі (i та i + ASRC_IN_SIZE) — T сусідніх кадрів завжди лежать підряд.
  int16_t in[2 * ASRC_IN_SIZE][2];
  volatile uint32_t wr;          // кадрів записано всього (лічильник іде по колу 2^32)
  uint64_t pos;                  // де читаємо: Q32.32 у вхідних кадрах (ціла частина — того ж лічильника)
  uint64_t step;                 // крок на вихідний кадр, Q32.32
  uint64_t step0;                // крок за номіналом (або за виміром частот)
  int taps;                      // відводів на фазу (парне)
  uint32_t fsIn, fsOut;          // номінали, Гц
  int built;                     // скільки фаз ваг уже пораховано (asrc_build)
  // Ваги, Q30 (фаза p — coef[p * taps …]). 16 біт (Q15) мало: на перевірці округлення ваг давало шум −81 дБ,
  // з 32 бітами — 95+ дБ (межа — сам 16-бітний вхід). 66 КБ ОЗП.
  int32_t coef[(ASRC_PHASES + 1) * ASRC_MAX_TAPS];
  // регулятор
  int32_t target;                // скільки кадрів тримати в запасі понад потрібні фільтру (у середньому)
  int32_t burst;                 // кадрів у пачці входу (AES — 192, PCM1808 — 16): запас «пиляє» на стільки
  float frac;                    // скільки кадрів «уже звучить», але ще не записано (з часу від останньої пачки)
  float lvl;                     // згладжений запас, кадрів
  float integ;                   // накопичена похибка регулятора
  float ppm;                     // нинішня поправка кроку, ppm (для звіту)
  uint32_t lastWr;               // лічильник запису на попередньому виклику регулятора
  uint32_t under;                // скільки разів бракувало вхідних кадрів (видано тишу)
  uint32_t over;                 // скільки разів кільце переповнилось (позицію пересунуто)
} asrc_t;

// Заготовити фільтр під пару частот. taps — парне, ≤ ASRC_MAX_TAPS. Обнуляє стан і позицію.
// target — запас «за часом» (див. asrc_steer), кадрів; burst — розмір пачки входу. Щоб між пачками не забракло,
// target має бути не менше burst + поле.
void asrc_init(asrc_t *a, uint32_t fsIn, uint32_t fsOut, int taps, int32_t target, int32_t burst);
// Те саме частинами (на RP2040 повний розрахунок ваг — ~0,3 с, а вихід не може стільки стояти):
// asrc_begin — параметри; asrc_build — до rows фаз ваг, true — усі готові; asrc_finish — обнулити й почати.
void asrc_begin(asrc_t *a, uint32_t fsIn, uint32_t fsOut, int taps, int32_t target, int32_t burst);
bool asrc_build(asrc_t *a, int rows);
void asrc_finish(asrc_t *a);
// Почати читати з запасом target «за часом» (після зміни джерела чи провалу).
void asrc_restart(asrc_t *a);
// Записати n стерео кадрів (int16 L,R підряд).
void asrc_write(asrc_t *a, const int16_t *lr, uint32_t n);
// Один вихідний кадр (24 біти в int32). false — вхідних кадрів забракло, видано тишу.
bool asrc_read(asrc_t *a, int32_t *l, int32_t *r);
// Запас понад потрібне фільтру, кадрів (може бути від'ємним — провал).
static inline int32_t asrc_level(const asrc_t *a) {
  return (int32_t)(a->wr - (uint32_t)(a->pos >> 32)) - a->taps / 2 - 1;
}
// Регулятор: викликати раз на n вихідних кадрів. Підправляє step за запасом «за часом»: frac — скільки кадрів
// надійшло б від останньої пачки, якби вхід ішов рівно (час від пачки × частота входу; 0…burst).
// Чому так: кадри приходять пачками (AES — раз на 4 мс), і запас, узятий як є, «пиляє» на цілу пачку; регулятор
// дивиться на нього раз на 1 мс — частоти майже кратні, і від пилки лишається повільна хвиля в кілька секунд,
// яку регулятор приймає за розбіжність кварців (на перевірці — гойдання ±300 ppm). Запас «за часом» — рівний.
void asrc_steer(asrc_t *a, uint32_t n, float frac);
// Задати крок за виміряними частотами (обидві — по тому ж годиннику), регулятор лишається.
void asrc_set_ratio(asrc_t *a, double fsInReal, double fsOutReal);
